if __name__ == "__main__":
    # Sample documents about machine learning
    ml_documents = [
        "Machine learning is a subset of artificial intelligence that focuses on algorithms that can learn from data.",
        "Supervised learning uses labeled data to train models that can make predictions on new, unseen data.",
        "Unsupervised learning finds patterns in data without labeled examples, such as clustering similar data points.",
        "Deep learning uses neural networks with multiple layers to learn complex patterns in data.",
        "Natural language processing applies machine learning techniques to understand and generate human language.",
        "Computer vision uses machine learning to interpret and understand visual information from images and videos.",
        "Reinforcement learning trains agents to make decisions by rewarding good actions and penalizing bad ones.",
        "Feature engineering is the process of selecting and transforming variables for use in machine learning models.",
        "Cross-validation is a technique used to evaluate machine learning models by testing on different data subsets.",
        "Overfitting occurs when a model learns the training data too well and performs poorly on new data."
    ]
    
    print("=== Multi-Query Retriever Example ===\n")
    
    # Create multi-query retriever
    multi_retriever = CustomMultiQueryRetriever()
    multi_retriever.create_vector_store(ml_documents)
    
    # Test query
    query = "How does ML work?"
    
    print(f"Original Query: {query}")
    
    # Get generated queries
    try:
        generated_queries = multi_retriever.get_generated_queries(query)
        print(f"\nGenerated Queries:")
        for i, q in enumerate(generated_queries, 1):
            print(f"{i}. {q}")
    except Exception as e:
        print(f"Could not generate queries: {e}")
    
    # Retrieve documents
    try:
        results = multi_retriever.retrieve(query)
        print(f"\nRetrieved Documents ({len(results)} found):")
        for i, doc in enumerate(results, 1):
            print(f"{i}. {doc.page_content}")
    except Exception as e:
        print(f"Could not retrieve documents: {e}")
    
    # Advanced multi-query retriever
    print("\n=== Advanced Multi-Query Retriever ===\n")
    
    advanced_retriever = AdvancedMultiQueryRetriever()
    advanced_retriever.create_vector_store(ml_documents)
    
    # Test with different strategies
    query2 = "What is deep learning?"
    
    print(f"Query: {query2}")
    
    # Perspective-based queries
    print("\nPerspective-based queries:")
    try:
        perspective_queries = advanced_retriever.generate_queries_by_perspective(query2)
        for i, q in enumerate(perspective_queries, 1):
            print(f"{i}. {q}")
    except Exception as e:
        print(f"Could not generate perspective queries: {e}")
    
    # Specificity-based queries
    print("\nSpecificity-based queries:")
    try:
        specificity_queries = advanced_retriever.generate_queries_by_specificity(query2)
        for i, q in enumerate(specificity_queries, 1):
            print(f"{i}. {q}")
    except Exception as e:
        print(f"Could not generate specificity queries: {e}")
    
    # Retrieve with fusion
    try:
        fusion_results = advanced_retriever.retrieve_with_fusion(query2, strategy="perspective")
        print(f"\nFusion Results ({len(fusion_results)} found):")
        for i, doc in enumerate(fusion_results, 1):
            print(f"{i}. {doc.page_content}")
    except Exception as e:
        print(f"Could not perform fusion retrieval: {e}")
